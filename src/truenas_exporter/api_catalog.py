# Defaults are restricted to documented subscription names that provide bounded
# operational telemetry and do not expose raw log streams or sensitive records.
# virt.instance.metrics (v25) was renamed to container.metrics (v26). Both carry
# the same bounded per-instance CPU/mem fields; the active compatibility profile
# filters the default to the one its TrueNAS version actually exposes.
DEFAULT_SAFE_EVENT_SUBSCRIPTIONS: tuple[str, ...] = (
    "reporting.realtime",
    "app.stats",
    "virt.instance.metrics",
    "container.metrics",
)

# Event schemas are full-object notifications and cannot be server-side
# selected. Only streams with owned, schema-specific parsers are allowed;
# every other documented event remains inventoried but blocked until it gains
# an equally bounded handler. This prevents credentials, arbitrary commands,
# descriptions, paths, identifiers, and high-cardinality configuration objects
# from reaching generic extraction.
SAFE_EVENT_SUBSCRIPTIONS: frozenset[str] = frozenset(
    DEFAULT_SAFE_EVENT_SUBSCRIPTIONS
)
UNSAFE_EVENT_SUBSCRIPTIONS: frozenset[str] = (
    DOCUMENTED_EVENT_NAMES - SAFE_EVENT_SUBSCRIPTIONS
)


def is_documented_read_only_method(method: str) -> bool:
    """Return whether *method* is documented as read-only for 25.10.2."""

    return method in READ_ONLY_METHOD_ALLOWLIST


def is_sensitive_read_method(method: str) -> bool:
    """Return whether fetching the full read response can expose sensitive data."""

    return method in SENSITIVE_READ_METHODS or method.startswith(SENSITIVE_NAMESPACE_PREFIXES)
